import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';
import { emptyValues, valueLibrary, valuesSchema } from '../lib/becoming/values';

test('Values assessment supports custom values, six keyboard-operable stages, and editable statements', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 900 });
  await page.goto('/becoming/values-assessment');
  await expect(page.getByRole('heading', { name: /Stage 1 of 6/ })).toBeVisible();
  await expect(page.getByText(/64 values/)).toBeVisible();
  await page.getByText('Add a custom value', { exact: true }).click();
  await page.getByRole('textbox', { name: 'Custom value name' }).fill('Attentive listening');
  await page.getByRole('textbox', { name: 'Definition' }).fill('Give others time to finish their thoughts.');
  await page.getByRole('button', { name: 'Add custom value' }).click();
  await expect(page.getByText('Attentive listening', { exact: true })).toBeVisible();
  const next = page.getByRole('button', { name: 'Next stage' });
  await next.click();
  await expect(next).toBeDisabled();
  const search = page.getByRole('searchbox', { name: 'Search values' });
  await search.fill('Attentive listening');
  await page.getByRole('checkbox', { name: /Attentive listening/ }).check();
  await search.clear();
  const important = page.getByRole('checkbox');
  for (const choice of (await important.all()).slice(0, 14)) await choice.check();
  await expect(page.getByText(/15 of 15 selected/)).toBeVisible();
  await expect(important.nth(14)).toBeDisabled();
  await next.click();
  await expect(page.getByRole('heading', { name: /Stage 3 of 6/ })).toBeFocused();
  for (const choice of (await page.getByRole('checkbox').all()).slice(0, 10)) await choice.check();
  await next.click();
  for (const choice of (await page.getByRole('checkbox').all()).slice(0, 5)) await choice.check();
  await next.click();
  const move = page.getByRole('button', { name: 'Move Kindness up' });
  await move.focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('listitem').filter({ hasText: 'Kindness' }).getByRole('button', { name: 'Move Kindness up' })).toBeDisabled();
  await next.click();
  const kindness = page.getByRole('group', { name: '1. Kindness' });
  await expect(kindness.getByRole('textbox')).toHaveCount(6);
  await kindness.getByRole('textbox', { name: 'Why does this matter to me?' }).fill('I can make time to listen.');
  await page.getByText(/Choose responses to include/).click();
  await page.getByRole('checkbox', { name: /Kindness.*Why does this matter/ }).check();
  await page.getByRole('textbox', { name: 'Template opening' }).fill('My priorities are {values}.');
  await page.getByRole('button', { name: 'Generate editable statement' }).click();
  const statement = page.getByRole('textbox', { name: 'Your values statement' });
  await expect(statement).toHaveValue(/My priorities are Kindness/);
  await expect(statement).toHaveValue(/I can make time to listen/);
  await statement.fill('I choose to listen with care.');
  await expect(statement).toHaveValue('I choose to listen with care.');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360);
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
});

test('Values library definitions and subset validation are complete', () => {
  expect(valueLibrary.length).toBeGreaterThanOrEqual(60);
  expect(new Set(valueLibrary.map(value => value.id)).size).toBe(valueLibrary.length);
  expect(valueLibrary.every(value => value.definition.length > 0)).toBe(true);
  expect(valuesSchema.safeParse({ ...emptyValues, selected: ['kindness'], shortlist: ['rest'] }).success).toBe(false);
  expect(valuesSchema.safeParse({ ...emptyValues, selected: ['kindness', 'kindness'] }).success).toBe(false);
});
